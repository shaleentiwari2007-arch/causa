/* ---------------- PDF ---------------- */

// jsPDF's built-in fonts only cover Latin-1, so normalise anything fancier
const pdfSafe = (value = '') =>
  String(value)
    .replace(/[\u2013\u2014]/g, '-')
    .replace(/[\u2018\u2019]/g, "'")
    .replace(/[\u201C\u201D]/g, '"')
    .replace(/\u2022/g, '*')
    .replace(/[\u2192\u2197\u2193]/g, '->')
    .replace(/[^\x20-\x7E\u00A0-\u00FF]/g, '')

function downloadChainPdf(result) {
  const doc = new jsPDF({ unit: 'pt', format: 'a4' })
  const margin = 52
  const pageWidth = doc.internal.pageSize.getWidth()
  const pageHeight = doc.internal.pageSize.getHeight()
  const width = pageWidth - margin * 2
  let y = margin

  const ensure = (needed) => {
    if (y + needed > pageHeight - margin) {
      doc.addPage()
      y = margin
    }
  }

  const write = (
    text,
    { size = 11, bold = false, color = [60, 64, 78], gap = 6, indent = 0 } = {},
  ) => {
    doc.setFont('helvetica', bold ? 'bold' : 'normal')
    doc.setFontSize(size)
    doc.setTextColor(...color)

    const lines = doc.splitTextToSize(pdfSafe(text), width - indent)
    const lineHeight = size * 1.4

    ensure(lines.length * lineHeight)
    doc.text(lines, margin + indent, y + size)
    y += lines.length * lineHeight + gap
  }

  const heading = (text) => {
    y += 8
    ensure(40)
    write(text, { size: 9, bold: true, color: [80, 110, 210], gap: 8 })
  }

  const label = result.domain ? result.domain.toUpperCase() : 'KNOWLEDGE'

  write(`CAUSA  |  CAUSAL TRACE  |  ${label}`, {
    size: 9,
    bold: true,
    color: [80, 110, 210],
    gap: 14,
  })
  write(result.title, { size: 28, bold: true, color: [18, 20, 32], gap: 4 })
  write(result.year, { size: 10, color: [120, 126, 142], gap: 14 })
  write(result.description, { size: 11.5, gap: 10 })

  heading('THE CHAIN')

  result.chain.forEach((step, index) => {
    const info = result.nodes?.[step] || relationshipData[step]

    ensure(48)
    write(
      `${String(index + 1).padStart(2, '0')}  ${step}${info?.type ? `   [${info.type}]` : ''}`,
      { size: 11.5, bold: true, color: [18, 20, 32], gap: 2 },
    )

    if (info?.description) {
      write(info.description, { size: 10, color: [95, 101, 118], indent: 22, gap: 8 })
    } else {
      y += 6
    }
  })

  heading('WHAT LED TO IT')
  result.causes.forEach((item) => write(`*  ${item}`, { size: 10.5, gap: 3 }))

  heading('WHAT CAME AFTER')
  result.effects.forEach((item) => write(`*  ${item}`, { size: 10.5, gap: 3 }))

  if (result.source === 'ai') {
    y += 14
    write(
      'Generated by CAUSA with AI assistance. AI-generated traces can contain errors - verify important facts.',
      { size: 8.5, color: [140, 146, 160] },
    )
  }

  const slug =
    pdfSafe(result.title)
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-|-$/g, '') || 'trace'

  doc.save(`${slug}-causa.pdf`)
}

/* ---------------- component ---------------- */

export default function Exploration({
  scope = null,
  initialQuery = '',
  onBack,
  onSwitchScope,
}) {
  const domain = getDomain(scope)

  const [query, setQuery] = useState(initialQuery)
  const [phase, setPhase] = useState('idle') // idle | loading | ok | offTopic | error
  const [result, setResult] = useState(null)
  const [message, setMessage] = useState('')
  const [stepIndex, setStepIndex] = useState(0)

  const controllerRef = useRef(null)
  const rootRef = useRef(null)
  const frameRef = useRef(0)

  // spotlight follows the pointer (CSS variables, no re-render)
  const handleMouseMove = (event) => {
    if (frameRef.current) return

    const { clientX, clientY } = event

    frameRef.current = window.requestAnimationFrame(() => {
      frameRef.current = 0
      rootRef.current?.style.setProperty('--mx', `${clientX}px`)
      rootRef.current?.style.setProperty('--my', `${clientY}px`)
    })
  }

  useEffect(
    () => () => {
      if (frameRef.current) window.cancelAnimationFrame(frameRef.current)
    },
    [],
  )

  const search = async (text) => {
    const value = (text ?? query).trim()
    if (value.length < 2) return

    controllerRef.current?.abort()
    const controller = new AbortController()
    controllerRef.current = controller

    setQuery(value)
    setResult(null)
    setMessage('')
    setPhase('loading')

    try {
      const outcome = await requestTrace(value, scope, { signal: controller.signal })
      if (controller.signal.aborted) return

      if (outcome.status === 'ok') {
        setResult(outcome.result)
        setPhase('ok')
      } else if (outcome.status === 'offTopic') {
        setMessage(outcome.reason)
        setPhase('offTopic')
      } else {
        setMessage(outcome.message)
        setPhase('error')
      }
    } catch (error) {
      if (error.name === 'AbortError') return
      setMessage('Something went wrong while tracing. Please try again.')
      setPhase('error')
    }
  }

  const closeResult = () => {
    setResult(null)
    setPhase('idle')
  }

  // deep link / "try in all knowledge" hand-off
  useEffect(() => {
    if (initialQuery) search(initialQuery)
    return () => controllerRef.current?.abort()
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [])

  // rotate the loading copy
  useEffect(() => {
    if (phase !== 'loading') return undefined

    setStepIndex(0)
    const id = window.setInterval(
      () => setStepIndex((index) => (index + 1) % LOADING_STEPS.length),
      1500,
    )

    return () => window.clearInterval(id)
  }, [phase])

  // Escape closes the result
  useEffect(() => {
    if (phase !== 'ok') return undefined

    const onKey = (event) => {
      if (event.key === 'Escape') closeResult()
    }

    window.addEventListener('keydown', onKey)
    return () => window.removeEventListener('keydown', onKey)
  }, [phase])

  const suggestions = domain ? domain.suggestions : ALL_SUGGESTIONS
  const resultDomain = result ? getDomain(result.domain) : null

  const curatedCount = domain
    ? chainsForDomain(scope).length
    : DOMAINS.reduce((total, item) => total + chainsForDomain(item.key).length, 0)

  const shareUrl = result
    ? `${window.location.origin}${window.location.pathname}?${
        scope ? `domain=${scope}&` : ''
      }q=${encodeURIComponent(result.query || result.title)}`
    : ''

  return (
    <section
      ref={rootRef}
      className="exploration"
      onMouseMove={handleMouseMove}
      style={{ '--domain-color': domain?.color || '#4d8cff' }}
    >
      <div className="exploration-stars" />
      <div className="exploration-aurora" />
      <div className="exploration-spotlight" />

      <header className="exploration-topbar">
        <div className="brand">
          <span className="brand-mark">C</span>
          <span>CAUSA</span>
        </div>

        <div className="system-status">
          <span className="status-dot" />
          {domain ? `${domain.name} DOMAIN ONLINE` : 'CAUSAL ENGINE ONLINE'}
        </div>

        <button type="button" className="return-button" onClick={onBack}>
          ← UNIVERSE
        </button>
      </header>

      <div className="exploration-content">
        <div className="domain-orb" aria-hidden="true">
          <span className="domain-orb-ring" />
          <span className="domain-orb-ring r2" />
          <span className="domain-orb-core" />
        </div>

        <div className="exploration-eyebrow">
          CAUSA / {domain ? domain.name : 'EXPLORATION ENGINE'}
        </div>

        <h2>
          {domain ? (
            <>
              VIEW IT THROUGH
              <br />
              <span className="domain-title">{domain.name}.</span>
            </>
          ) : (
            <>
              WHAT DO YOU WANT
              <br />
              <span>TO UNDERSTAND?</span>
            </>
          )}
        </h2>

        <p className="exploration-description">
          {domain
            ? `${domain.tagline} Search anything — CAUSA traces it through the lens of ${domain.name.toLowerCase()} only.`
            : "Don't search for an answer. Trace what caused it."}
        </p>

        <div className="domain-stats">
          <div>
            <span>LENS</span>
            <strong className="accent">{domain ? domain.name : 'ALL DOMAINS'}</strong>
          </div>
          <div>
            <span>CURATED TRACES</span>
            <strong>{String(curatedCount).padStart(2, '0')}</strong>
          </div>
          <div>
            <span>AI TRACES</span>
            <strong>ON DEMAND</strong>
          </div>
          <div>
            <span>STATUS</span>
            <strong>ONLINE</strong>
          </div>
        </div>

        <div className="scope-switcher" aria-label="Knowledge domain">
          <button
            type="button"
            className={`scope-chip ${!scope ? 'active' : ''}`}
            aria-pressed={!scope}
            onClick={() => scope && onSwitchScope(null)}
          >
            <span className="scope-dot" />
            ALL
          </button>

          {DOMAINS.map((item) => (
            <button
              key={item.key}
              type="button"
              className={`scope-chip ${scope === item.key ? 'active' : ''}`}
              style={{ '--chip-color': item.color }}
              aria-pressed={scope === item.key}
              onClick={() => scope !== item.key && onSwitchScope(item.key)}
            >
              <span className="scope-dot" />
              {item.name}
            </button>
          ))}
        </div>

        <div className="search-container">
          <input
            value={query}
            maxLength={120}
            onChange={(event) => setQuery(event.target.value)}
            onKeyDown={(event) => {
              if (event.key === 'Enter') search()
            }}
            aria-label="Search CAUSA"
            placeholder={
              domain
                ? `Search anything through the lens of ${domain.name.toLowerCase()}…`
                : 'Try "telegraph", "vaccines", or "the internet"'
            }
          />

          <button type="button" onClick={() => search()} aria-label="Search CAUSA">
            ↗
          </button>
        </div>

        {phase === 'loading' && (
          <div className="trace-loading" role="status" aria-live="polite">
            <div className="trace-loading-orbit">
              <span />
              <span />
              <span />
            </div>

            <div className="trace-loading-copy">
              <strong>TRACING CAUSALITY{domain ? ` · ${domain.name} LENS` : ''}</strong>
              <span>{LOADING_STEPS[stepIndex]}…</span>
            </div>
          </div>
        )}

        {phase === 'error' && <div className="search-empty">{message}</div>}

        {phase === 'offTopic' && (
          <div className="search-empty">
            {message}
            {scope && (
              <button
                type="button"
                className="search-empty-action"
                onClick={() => onSwitchScope(null, query)}
              >
                TRACE IT IN ALL KNOWLEDGE ↗
              </button>
            )}
          </div>
        )}

        <div className="suggestions">
          <span className="suggestions-label">TRY</span>

          {suggestions.map((item) => (
            <button
              key={item}
              type="button"
              className="suggestion-chip"
              onClick={() => search(item)}
            >
              {item}
            </button>
          ))}
        </div>

        {domain ? (
          <div className="featured">
            <span className="featured-label">CURATED TRACES · {domain.name}</span>

            <div className="featured-grid">
              {chainsForDomain(scope).map((chain) => (
                <button
                  key={chain.title}
                  type="button"
                  className="featured-card"
                  onClick={() => search(chain.title)}
                >
                  <span>{chain.year}</span>
                  <strong>{chain.title}</strong>
                  <p>{chain.description}</p>

                  <div className="featured-path">
                    {chain.chain.slice(0, 4).map((step) => (
                      <i key={step}>{step}</i>
                    ))}
                    {chain.chain.length > 4 && (
                      <i className="more">+{chain.chain.length - 4}</i>
                    )}
                  </div>

                  <em className="featured-open">TRACE IT ↗</em>
                </button>
              ))}
            </div>
          </div>
        ) : (
          <div className="featured">
            <span className="featured-label">ENTER A DOMAIN</span>

            <div className="domain-grid tile-grid">
              {DOMAINS.map((item) => (
                <button
                  key={item.key}
                  type="button"
                  className="domain-tile"
                  style={{ '--domain-color': item.color }}
                  onClick={() => onSwitchScope(item.key)}
                >
                  <span className="domain-tile-glow" />
                  <span className="domain-dot" />
                  <strong>{item.name}</strong>
                  <p>{item.tagline}</p>
                  <em>
                    {String(chainsForDomain(item.key).length).padStart(2, '0')} CURATED ·
                    AI ON DEMAND ↗
                  </em>
                </button>
              ))}
            </div>
          </div>
        )}

        {phase === 'ok' && result && (
          <div className="causal-overlay">
            <div className="causal-overlay-backdrop" onClick={closeResult} />

            <div
              className="causal-result"
              role="dialog"
              aria-modal="true"
              aria-label="Causal trace"
            >
              <button
                type="button"
                className="causal-close"
                onClick={closeResult}
                aria-label="Close causal trace"
              >
                ×
              </button>

              <div className="result-header">
                <div>
                  <span>
                    {result.source === 'ai' ? 'AI-GENERATED TRACE' : 'CURATED TRACE'}
                    {resultDomain ? ` · ${resultDomain.name}` : ''}
                  </span>
                  <h3>{result.title}</h3>
                </div>

                <span>{result.year}</span>
              </div>

              <p>{result.description}</p>

              {result.source === 'ai' && (
                <div className="result-note">
                  AI-generated trace. It can contain mistakes, so verify important facts.
                </div>
              )}

              <CausalTrace result={result} />

              <div className="result-columns">
                <div>
                  <span>WHAT LED TO IT</span>
                  <ul>
                    {result.causes.map((cause) => (
                      <li key={cause}>{cause}</li>
                    ))}
                  </ul>
                </div>

                <div>
                  <span>WHAT CAME AFTER</span>
                  <ul>
                    {result.effects.map((effect) => (
                      <li key={effect}>{effect}</li>
                    ))}
                  </ul>
                </div>
              </div>

              <div className="share-panel">
                <div className="share-info">
                  <span>SHARE THIS TRACE</span>
                  <p>
                    Scan to open this exact trace on another device, or download it as a
                    PDF right now.
                  </p>
                  <button
                    type="button"
                    className="pdf-button"
                    onClick={() => downloadChainPdf(result)}
                  >
                    DOWNLOAD PDF ⬇
                  </button>
                </div>

                <div className="qr-wrap">
                  <QRCode value={shareUrl} size={92} bgColor="#ffffff" fgColor="#05060f" />
                </div>
              </div>

              <CausalityGraph result={result} />
            </div>
          </div>
        )}
      </div>
    </section>
  )
}